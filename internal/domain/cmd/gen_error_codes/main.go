// gen_error_codes scans the domain package for all newError(...) calls,
// extracts the code (first argument) and message (second argument), and writes
// them as an OpenAPI enum schema with x-enumDescriptions to the path given as
// the first CLI argument.
//
// Usage (via go:generate):
//
//	go run ./cmd/gen_error_codes ../../api/openapi/components/schemas/error-code.yaml
package main

import (
	"fmt"
	"go/ast"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

type errorEntry struct {
	code    string
	message string
}

func main() {
	if len(os.Args) < 2 {
		fmt.Fprintln(os.Stderr, "usage: gen_error_codes <output-yaml-path>")
		os.Exit(1)
	}
	outPath := os.Args[1]

	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax,
	}
	pkgs, err := packages.Load(cfg, "github.com/zitadel/nextgen/internal/domain")
	if err != nil {
		fmt.Fprintf(os.Stderr, "load error: %v\n", err)
		os.Exit(1)
	}

	var entries []errorEntry
	seen := map[string]bool{}

	for _, pkg := range pkgs {
		for _, file := range pkg.Syntax {
			ast.Inspect(file, func(n ast.Node) bool {
				call, ok := n.(*ast.CallExpr)
				if !ok {
					return true
				}
				fn, ok := call.Fun.(*ast.Ident)
				if !ok || fn.Name != "newError" {
					return true
				}
				if len(call.Args) < 2 {
					return true
				}
				codeLit, ok := call.Args[0].(*ast.BasicLit)
				if !ok || codeLit.Kind != token.STRING {
					return true
				}
				msgLit, ok := call.Args[1].(*ast.BasicLit)
				if !ok || msgLit.Kind != token.STRING {
					return true
				}
				code := strings.Trim(codeLit.Value, `"`)
				msg := strings.Trim(msgLit.Value, `"`)
				if !seen[code] {
					seen[code] = true
					entries = append(entries, errorEntry{code: code, message: msg})
				}
				return true
			})
		}
	}

	sort.Slice(entries, func(i, j int) bool {
		return entries[i].code < entries[j].code
	})

	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "mkdir error: %v\n", err)
		os.Exit(1)
	}

	var sb strings.Builder
	sb.WriteString("# Code generated by internal/domain/cmd/gen_error_codes/main.go; DO NOT EDIT.\n")
	sb.WriteString("type: string\n")
	sb.WriteString("description: Stable machine-readable error code.\n")
	sb.WriteString("enum:\n")
	for _, e := range entries {
		fmt.Fprintf(&sb, "  - %s\n", e.code)
	}
	sb.WriteString("x-enumDescriptions:\n")
	for _, e := range entries {
		fmt.Fprintf(&sb, "  %s: %s\n", e.code, e.message)
	}
	if len(entries) > 0 {
		fmt.Fprintf(&sb, "example: %s\n", entries[0].code)
	}

	if err := os.WriteFile(outPath, []byte(sb.String()), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write error: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("wrote %d error code(s) to %s\n", len(entries), outPath)
}
