import { writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { bundle, loadConfig } from "@redocly/openapi-core";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(packageRoot, "../..");
const input = resolve(repoRoot, "apps/api/api/openapi/openapi-spec.yaml");
const output = resolve(packageRoot, "src/generated/errors.ts");

/** The slice of a dereferenced schema this reads: an error is an object whose `code` is a constant. */
type Schema = {
  properties?: Record<string, { const?: unknown; enum?: unknown[] }>;
  allOf?: Schema[];
};

/**
 * Writes `src/generated/errors.ts`: one error class per `code` the spec names,
 * and the lookup `customFetch` throws them by. orval runs it after it has
 * written the client (`hooks.afterAllFilesWrite` in `orval.config.ts`), so it
 * reads the spec under the same lock and in the same task.
 */
export async function writeErrors(): Promise<void> {
  const config = await loadConfig({ configPath: resolve(repoRoot, "redocly.yaml") });
  const { bundle: result } = await bundle({ ref: input, config, dereference: true });
  await writeFile(output, errorsSource(errorCodes(result.parsed)));
}

/**
 * Every error code the document names, sorted: each schema, wherever it sits
 * (a component, an operation's response, a branch of a `oneOf`), whose `code`
 * property is a single constant.
 */
export function errorCodes(document: unknown): string[] {
  const codes = new Set<string>();
  const seen = new Set<object>();
  const walk = (node: unknown): void => {
    if (node === null || typeof node !== "object" || seen.has(node)) {
      return;
    }
    seen.add(node);
    const code = codeOf(node as Schema);
    if (code !== undefined) {
      codes.add(code);
    }
    for (const child of Object.values(node)) {
      walk(child);
    }
  };
  walk(document);
  return [...codes].sort();
}

/** The constant a schema fixes its `code` to, its `allOf` parts' included. */
function codeOf(schema: Schema): string | undefined {
  for (const part of [schema, ...(Array.isArray(schema.allOf) ? schema.allOf : [])]) {
    const code = part.properties?.code;
    const value = code?.const ?? (code?.enum?.length === 1 ? code.enum[0] : undefined);
    if (typeof value === "string") {
      return value;
    }
  }
  return undefined;
}

/**
 * The class a code becomes: its words, capitalised, then `Error`, so
 * `proj.not_found` is `ProjNotFoundError`.
 */
export function errorClassName(code: string): string {
  return `${code
    .split(/[._]/)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("")}Error`;
}

/** The source of `src/generated/errors.ts` for the codes a spec names. */
export function errorsSource(codes: readonly string[]): string {
  const names = new Map<string, string>();
  for (const code of codes) {
    const name = errorClassName(code);
    const clash = names.get(name);
    if (clash !== undefined) {
      throw new Error(`the codes ${clash} and ${code} both make the class ${name}`);
    }
    names.set(name, code);
  }
  const classes = codes.map(
    (code) =>
      `/** The server answered \`${code}\`. */\nexport class ${errorClassName(code)} extends ApiError {\n  override readonly name = ${JSON.stringify(errorClassName(code))};\n  readonly code = ${JSON.stringify(code)};\n}`,
  );
  const table = codes.map((code) => `  ${JSON.stringify(code)}: ${errorClassName(code)},`);
  return `// Code generated by packages/api/scripts/errors.ts from api/openapi. DO NOT EDIT: regenerate with moon run api:generate.

import { ApiError } from "../runtime/api-error";

${classes.join("\n\n")}

/** Each class by the code it is thrown for. */
export const errorClasses = {
${table.join("\n")}
} as const;

/** A code the spec names. */
export type ErrorCode = keyof typeof errorClasses;

/**
 * The class for a code the server answered with.
 *
 * @returns The class, or undefined for a code the spec does not name, as from
 * a newer server.
 */
export function errorClassFor(code: string | undefined): (typeof errorClasses)[ErrorCode] | undefined {
  return code !== undefined && Object.hasOwn(errorClasses, code)
    ? errorClasses[code as ErrorCode]
    : undefined;
}
`;
}
