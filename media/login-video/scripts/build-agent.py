"""Turn the agent recordings (scripts/agent-rec.py) into the steps the agent pane shows.

usage: python3 build-agent.py <app dir> <prompt1.jsonl> <prompt2.jsonl> -> data/agent.js
Keeps the run's order and real times. What a viewer needs stays a line of its own:
the agent's sentences (first sentence each), every Zitadel CLI command, the files
it wrote and its checks. Reads, help lookups and attempts the run's permissions
refused fold into "Read n files" lines. Paths are shown relative to the app.
"""
import json, os, re, sys

app = os.path.realpath(sys.argv[1])
VID = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FOLDED_SAYS = re.compile(r"blocked|approval|instead|couldn't|could not", re.I)


def rel(p):
    p = os.path.realpath(p) if p.startswith("/") else p
    return os.path.relpath(p, app) if p.startswith(app) else p


def first_sentence(text, n=118):
    text = re.sub(r"\*\*|`", "", text.strip().split("\n")[0])
    m = re.match(r"(.+?[.:!?])(\s|$)", text)
    s = m.group(1) if m else text
    return s if len(s) <= n else s[: n - 1].rstrip() + "…"


def build(path):
    events = [json.loads(l) for l in open(path)]
    prompt, total, steps, reads = None, 0.0, [], []
    refused = set()
    for r in events:
        e = r["e"]
        if e.get("type") == "user":
            for c in e["message"].get("content", []):
                if isinstance(c, dict) and c.get("type") == "tool_result" and c.get("is_error"):
                    refused.add(c["tool_use_id"])

    def flush(t):
        if reads:
            n = len(reads)
            steps.append({"t": reads[0], "kind": "read", "text": f"Read {n} file{'s' if n > 1 else ''}"})
            reads.clear()

    def add(t, kind, text):
        if kind != "read":
            flush(t)
        if kind == "edit" and steps and steps[-1]["kind"] == "edit" and steps[-1]["text"] == text:
            return
        steps.append({"t": t, "kind": kind, "text": text})

    for r in events:
        e, t = r["e"], r["t"]
        if e.get("type") == "result":
            total = t
            continue
        if e.get("type") != "assistant":
            continue
        for c in e["message"]["content"]:
            if c["type"] == "text" and c["text"].strip():
                s = first_sentence(c["text"])
                if not FOLDED_SAYS.search(s):
                    add(t, "say", s)
            if c["type"] != "tool_use":
                continue
            name, i = c["name"], c["input"]
            if c["id"] in refused and name not in ("Edit", "Write"):
                reads.append(t)
                continue
            if name == "Skill":
                add(t, "skill", f"Using the {i['skill']} skill")
            elif name in ("Read", "Grep", "Glob"):
                reads.append(t)
            elif name in ("Edit", "Write"):
                add(t, "edit", rel(i["file_path"]))
            elif name == "Bash":
                cmd = re.sub(r"\s*[12]?>\s*\S+.*$", "", i["command"].split("\n")[0]).strip()
                if re.match(r"npx (-y )?@zitadel/cli\S* (setup|deploy|doctor|start)\b", cmd) and "--help" not in cmd:
                    kind = "check" if " doctor" in cmd else "run"
                    add(t, kind, re.sub(r"^npx -y ", "npx ", cmd))
                elif re.match(r"npm run (build|lint)", cmd):
                    add(t, "check", re.sub(r"\s*\|.*$", "", cmd))
                elif cmd.startswith("npm run dev"):
                    add(t, "run", "npm run dev")
                elif cmd.startswith(("curl", "for p in")):
                    if not (steps and steps[-1]["text"] == "Checked the pages respond"):
                        add(t, "check", "Checked the pages respond")
                else:
                    reads.append(t)
            # ToolSearch, TaskStop and the like are housekeeping, not steps
    flush(total)
    for e in events:
        if e["e"].get("type") == "user":
            for c in e["e"]["message"].get("content", []):
                if isinstance(c, str):
                    prompt = c
                    break
                if isinstance(c, dict) and c.get("type") == "text":
                    prompt = c["text"]
                    break
        if prompt:
            break
    return {"total": round(total, 1), "steps": steps}


runs = [build(p) for p in sys.argv[2:]]
out = os.path.join(VID, "data", "agent.js")
with open(out, "w") as f:
    f.write("// generated by scripts/build-agent.py from the agent recordings\n")
    f.write("window.AGENT = " + json.dumps(runs, separators=(",", ":")) + ";\n")
for k, run in enumerate(runs, 1):
    print(f"prompt {k}: {run['total']} s, {len(run['steps'])} steps")
    for s in run["steps"]:
        print(f"  {s['t']:6.1f} {s['kind']:5} {s['text']}")
