/**
 * Writes what the Go login SDK embeds from the rest of the monorepo, so the
 * published module needs no other package:
 *
 * - the login copy the components package holds in
 *   `packages/components/src/orchestrator/locales/{en,de,it}.ts`, as JSON
 *   under `packages/go/login/locales/`. The TS catalogs stay the one home for
 *   login copy; this only exports them. Keys are sorted by code point so the
 *   output is stable whatever order the catalogs list them in; the leading
 *   `$comment` is the marker scripts/generated-outputs.mjs checks before it
 *   deletes a file.
 * - the `--zl-*` stylesheet `packages/design-tokens/src/generated/tokens.css`,
 *   copied to `packages/go/login/assets/tokens.css` under a header naming
 *   this script, so a reader is not sent to the tokens' own generator.
 * - the `<zl-passkey>` atom as the self-contained
 *   `packages/components/dist/passkey-standalone.mjs`, copied to
 *   `packages/go/login/assets/passkey-standalone.mjs` under the same header.
 *   It is a build output, so `@zitadel/server#generate` and `#check-generate`
 *   depend on `@zitadel/components#build` (apps/server/turbo.json).
 *
 *   corepack pnpm exec tsx scripts/generate-go-login-assets.ts
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { de } from "../packages/components/src/orchestrator/locales/de.js";
import { en } from "../packages/components/src/orchestrator/locales/en.js";
import { it } from "../packages/components/src/orchestrator/locales/it.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
// scripts/go-generate.mjs runs this in a copy of the tree holding the files
// git tracks, with no ignored build output: it names the real tree in
// ZITADEL_SOURCE_ROOT so a built file is read from there. Run in place (a bare
// `go generate`), this tree is the real one.
const BUILT_ROOT = process.env.ZITADEL_SOURCE_ROOT ?? ROOT;
const OUT_DIR = join(ROOT, "packages/go/login/locales");
const MARKER = "Code generated by scripts/generate-go-login-assets.ts; DO NOT EDIT.";

mkdirSync(OUT_DIR, { recursive: true });
for (const [tag, catalog] of Object.entries({ en, de, it })) {
  const sorted = Object.fromEntries(
    Object.entries(catalog).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
  );
  const outPath = join(OUT_DIR, `${tag}.json`);
  writeFileSync(outPath, `${JSON.stringify({ $comment: MARKER, ...sorted }, null, 2)}\n`);
  console.log(`locales/${tag}.ts → ${outPath.slice(ROOT.length + 1)}`);
}

const TOKENS = "packages/design-tokens/src/generated/tokens.css";
const TOKENS_OUT = "packages/go/login/assets/tokens.css";
// The source names its own generator, whose re-run does not reach this copy.
writeFileSync(
  join(ROOT, TOKENS_OUT),
  `/* ${MARKER} Source: ${TOKENS}; re-run: turbo run generate --filter=@zitadel/server */\n${readFileSync(join(ROOT, TOKENS), "utf8")}`,
);
console.log(`${TOKENS} → ${TOKENS_OUT}`);

const PASSKEY = "packages/components/dist/passkey-standalone.mjs";
const PASSKEY_OUT = "packages/go/login/assets/passkey-standalone.mjs";
writeFileSync(
  join(ROOT, PASSKEY_OUT),
  `// ${MARKER} Source: ${PASSKEY}; re-run: turbo run generate --filter=@zitadel/server\n${readFileSync(join(BUILT_ROOT, PASSKEY), "utf8")}`,
);
console.log(`${PASSKEY} → ${PASSKEY_OUT}`);
