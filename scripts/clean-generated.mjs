#!/usr/bin/env node
/**
 * Deletes every Go code-generation output.
 *
 * Generators only ever write; they never retract. When a directive changes
 * destination, or an interface stops being mocked, the old file stays on disk
 * and stays committed — still compiling, still imported, quietly wrong. Adding
 * a mock to `internal/service` and re-running generate will not tell you that
 * `mocks/statement.mock.go` has been dead for a month.
 *
 * So the way to prune is to remove everything and regenerate:
 *
 *     moon run server:clean-generated && moon run server:generate
 *
 * Whatever does not come back was orphaned. `server:generate` bootstraps from
 * an empty tree (it runs enumer before mockgen — see scripts/go-generate.mjs),
 * so this is safe to run at any time.
 *
 * Deletion is guarded twice: the globs are file-precise, and every file must
 * additionally carry a "generated by … DO NOT EDIT" marker. Anything matching
 * a glob without a marker is reported and left alone.
 */
import { rmSync } from "node:fs";
import { join } from "node:path";

import { isDirectRun } from "./dev-process.mjs";
import { collectGeneratedFiles, ROOT } from "./generated-outputs.mjs";

export function cleanGenerated({ dryRun = false, quiet = false, log = console.log } = {}) {
  // check-go-generate calls this as a step inside a larger check, where a
  // 118-line inventory is noise rather than information.
  const emit = quiet ? () => undefined : log;
  const { generated, unmarked } = collectGeneratedFiles();

  for (const rel of generated) {
    if (!dryRun) {
      rmSync(join(ROOT, rel));
    }
    emit(`${dryRun ? "would remove" : "removed"} ${rel}`);
  }

  if (unmarked.length > 0) {
    // Not fatal: the file may be hand-written and wrongly matched, which is
    // exactly the case the marker check exists to protect.
    emit("");
    emit(`kept ${unmarked.length} file(s) matching an output glob without a generated marker:`);
    for (const rel of unmarked) {
      emit(`  ${rel}`);
    }
    emit("Check whether the globs in scripts/generated-outputs.mjs are too broad.");
  }

  emit("");
  emit(`${dryRun ? "would remove" : "removed"} ${generated.length} generated file(s)`);
  if (!dryRun) {
    emit("run `moon run server:generate` to regenerate; anything not restored was orphaned");
  }
  return { removed: generated, unmarked };
}

if (isDirectRun(import.meta.url)) {
  cleanGenerated({ dryRun: process.argv.includes("--dry-run") });
}
