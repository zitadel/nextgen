#!/usr/bin/env node
import { appendFile, readFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import {
  embeddedServerSurfaces,
  gitChangedEntries,
  isTestFile,
  publicPackages,
} from "./check-changesets-status.mjs";
import { forwardedArgs, isDirectRun, runCapture } from "./dev-process.mjs";

// Roots whose contents reach a customer: the published npm packages plus the
// UIs built into the server container. Derived from the release manifest so this
// list cannot drift from what actually ships.
const PUBLISHED_ROOTS = [...publicPackages, ...embeddedServerSurfaces].map((pkg) => pkg.root);

const repoRoot = fileURLToPath(new URL("..", import.meta.url));

// Types whose PR lands in customer-facing release notes. A change that reaches
// nobody outside this repo must not claim one of them.
const CUSTOMER_TYPES = new Set(["feat", "fix"]);

// Types that assert the opposite — that nothing a user receives changed. When a
// shipping path moved, that assertion is usually wrong (see #526 and #482 in
// CONTRIBUTING.md#title-format), but it is not fully derivable from paths, so
// this warns instead of failing.
const NON_CUSTOMER_TYPES = new Set(["docs", "chore"]);

const NON_SHIPPING_TOP_LEVEL_DIRS = [
  ".changeset",
  ".devcontainer",
  ".github",
  ".moon",
  ".run",
  "docs",
  "examples",
  "scripts",
  "tools",
];

// Workspaces that build or exercise the product without ever reaching a user:
// mocks, demos, and the docs site. (`packages/testing` left this list when it
// joined the release train in #692 — the manifest-derived PUBLISHED_ROOTS
// covers it now.)
const NON_SHIPPING_WORKSPACES = [
  "apps/docs/",
  "apps/mock-zitadel/",
  "apps/storybook/",
  "packages/api-mock/",
];

// Repo-meta markdown, wherever it sits. Every other `.md` is treated as shipping
// on purpose: `packages/config/defaults/README-*.md` and the CLI's framework
// READMEs are scaffolded into a customer's project, so a change there is product.
// Repo-meta markdown wherever it sits. CHANGELOG.md stays here on purpose: it is
// generated by `changeset version`, so a version PR rewriting it is not shipping
// work. AGENTS.md matches the exemption `packageForFile()` already applies.
const REPO_META_MARKDOWN = new Set(["AGENTS.md", "CHANGELOG.md", "CONTRIBUTING.md"]);

// Files that ship only when their package does — a README under
// `packages/design-tokens/` (a build input, never published) reaches nobody, while
// `packages/sdk-react/README.md` is the page a customer reads on npm. `SKILLS.md`
// is here because `apps/cli/package.json` lists it in `files`, so the CLI agent
// contract is installed alongside the binary.
const PUBLISHED_ONLY_FILENAMES = new Set(["README.md", "package.json", "SKILLS.md"]);

const NON_SHIPPING_ROOT_FILES = new Set([
  "Dockerfile",
  "LICENSE",
  "devbox.json",
  "devbox.lock",
  "go.sum",
  "main.go",
  "moon.yml",
  "package.json",
  "pnpm-lock.yaml",
  "pnpm-workspace.yaml",
  "redocly.yaml",
  "tsconfig.base.json",
  "tsconfig.json",
  "vitest.workspace.ts",
]);

export function parseSemanticConfig(source) {
  const types = [];
  const scopes = [];
  let current;

  for (const rawLine of source.split(/\r?\n/)) {
    const line = rawLine.replace(/\s+#.*$/, "").trimEnd();
    if (!line || line.trimStart().startsWith("#")) {
      continue;
    }

    const topLevel = line.match(/^([A-Za-z][\w-]*):\s*(.*)$/);
    if (topLevel) {
      current = topLevel[1] === "types" ? types : topLevel[1] === "scopes" ? scopes : undefined;
      continue;
    }

    const item = line.match(/^\s+-\s+(.+)$/);
    if (item && current) {
      current.push(item[1].trim());
    }
  }

  return { types, scopes };
}

export function parseConventionalTitle(title) {
  const match = String(title ?? "")
    .trim()
    .match(/^([a-z]+)(?:\(([^)]*)\))?(!)?:\s+(\S.*)$/);

  if (!match) {
    return { ok: false };
  }

  return {
    ok: true,
    type: match[1],
    scope: match[2],
    breaking: Boolean(match[3]),
    summary: match[4].trim(),
  };
}

export function isNonShippingFile(file) {
  const path = String(file).replaceAll("\\", "/");

  if (isTestFile(path) || path.includes("/testdata/")) {
    return true;
  }

  const [top] = path.split("/");
  if (path.includes("/") && NON_SHIPPING_TOP_LEVEL_DIRS.includes(top)) {
    return true;
  }

  if (!path.includes("/")) {
    // Root-level file: dotfiles, config, and repo docs never ship.
    return path.startsWith(".") || path.endsWith(".md") || NON_SHIPPING_ROOT_FILES.has(path);
  }

  if (NON_SHIPPING_WORKSPACES.some((workspace) => path.startsWith(workspace))) {
    return true;
  }

  // End-to-end suites live beside the app they exercise and ship with none of it.
  if (/^apps\/[^/]*-e2e\//.test(path) || /^apps\/demo-[^/]+\//.test(path)) {
    return true;
  }

  if (path.endsWith("/moon.yml")) {
    return true;
  }

  // Build tooling inside a package, mirroring the root `scripts/` exclusion: it
  // produces what ships without shipping itself.
  if (path.includes("/scripts/")) {
    return true;
  }

  // Contributor documentation wherever it sits, e.g. `apps/console/docs/`. No
  // package packs a `docs/` directory, so none of it reaches a customer.
  if (path.includes("/docs/")) {
    return true;
  }

  const basename = path.split("/").at(-1) ?? "";
  if (REPO_META_MARKDOWN.has(basename)) {
    return true;
  }
  if (PUBLISHED_ONLY_FILENAMES.has(basename)) {
    return !PUBLISHED_ROOTS.some((root) => path.startsWith(root));
  }

  return false;
}

export function suggestType(files) {
  const paths = files.map((file) => String(file).replaceAll("\\", "/"));
  if (paths.length === 0) {
    return "chore";
  }
  if (
    paths.every(
      (path) =>
        isTestFile(path) ||
        path.includes("/testdata/") ||
        /^apps\/[^/]*-e2e\//.test(path) ||
        /^apps\/demo-[^/]+\//.test(path) ||
        path.startsWith("apps/mock-zitadel/") ||
        path.startsWith("packages/api-mock/"),
    )
  ) {
    return "test";
  }
  if (paths.every((path) => path.startsWith(".github/"))) {
    return "ci";
  }
  if (paths.every((path) => path.endsWith(".md"))) {
    return "docs";
  }
  return "build";
}

export function checkPrTitle(options) {
  const title = String(options.title ?? "").trim();
  const files = (options.files ?? []).map((file) => String(file).replaceAll("\\", "/"));
  const config = options.config ?? { types: [], scopes: [] };
  const errors = [];
  const warnings = [];

  const parsed = parseConventionalTitle(title);
  if (!parsed.ok) {
    errors.push({
      code: "unparseable-title",
      message: `title must be "<type>(optional-scope): <summary>", got: ${title || "(empty)"}`,
    });
    return report({ title, parsed, files, errors, warnings });
  }

  if (config.types.length > 0 && !config.types.includes(parsed.type)) {
    errors.push({
      code: "unknown-type",
      message: `type "${parsed.type}" is not in .github/semantic.yml (allowed: ${config.types.join(", ")})`,
    });
  }

  if (
    parsed.scope !== undefined &&
    config.scopes.length > 0 &&
    !config.scopes.includes(parsed.scope)
  ) {
    errors.push({
      code: "unknown-scope",
      message: `scope "${parsed.scope}" is not in .github/semantic.yml — omit the scope rather than invent one`,
    });
  }

  const shipping = files.filter((file) => !isNonShippingFile(file));

  if (files.length > 0 && shipping.length === 0 && CUSTOMER_TYPES.has(parsed.type)) {
    errors.push({
      code: "non-shipping-customer-type",
      message:
        `"${parsed.type}" claims a customer-visible change, but no changed file reaches a user of ` +
        `the SDKs, CLI, API, console, or login UI. Use "${suggestType(files)}:" instead, or explain ` +
        `which shipped surface this changes. Rule: CONTRIBUTING.md#title-format`,
    });
  }

  if (shipping.length > 0 && NON_CUSTOMER_TYPES.has(parsed.type)) {
    warnings.push({
      code: "shipping-non-customer-type",
      message:
        `"${parsed.type}" asserts nothing a user receives changed, but this PR touches shipped ` +
        `paths (${shipping.slice(0, 3).join(", ")}${shipping.length > 3 ? ", …" : ""}). If a customer ` +
        `gets something different, use "feat" or "fix" and add a changeset.`,
    });
  }

  return report({ title, parsed, files, shipping, errors, warnings });
}

function report({ title, parsed, files, shipping = [], errors, warnings }) {
  return {
    ok: errors.length === 0,
    title,
    parsed,
    files,
    shipping,
    nonShipping: files.filter((file) => isNonShippingFile(file)),
    errors,
    warnings,
    nextAction: nextAction({ errors, warnings, parsed }),
  };
}

function nextAction({ errors, warnings, parsed }) {
  if (errors.some((error) => error.code === "unparseable-title")) {
    return 'Retitle as "<type>(optional-scope): <summary>" — see CONTRIBUTING.md#title-format.';
  }
  if (errors.some((error) => error.code === "non-shipping-customer-type")) {
    return `Retype away from "${parsed.type}": this PR reaches no one outside the repo.`;
  }
  if (errors.length > 0) {
    return "Fix the title against .github/semantic.yml, then rerun this check.";
  }
  if (warnings.length > 0) {
    return "Confirm the type is honest about what a customer receives, then merge.";
  }
  return "Title type matches what this PR ships.";
}

export function renderStepSummary(report) {
  const lines = [
    "# PR title",
    "",
    `Title: \`${report.title}\``,
    `Status: ${report.ok ? "passed" : "failed"}`,
    "",
  ];

  if (report.parsed.ok) {
    lines.push(
      `Type: \`${report.parsed.type}\`${report.parsed.scope ? ` · scope \`${report.parsed.scope}\`` : ""}`,
      "",
    );
  }

  lines.push(
    `Changed files: ${report.files.length} (${report.shipping.length} on a shipping surface)`,
    "",
  );

  if (report.errors.length > 0) {
    lines.push("## Errors", "");
    for (const error of report.errors) {
      lines.push(`- ${error.message}`);
    }
    lines.push("");
  }

  if (report.warnings.length > 0) {
    lines.push("## Warnings", "");
    for (const warning of report.warnings) {
      lines.push(`- ${warning.message}`);
    }
    lines.push("");
  }

  lines.push("## Next action", "", report.nextAction, "");
  return `${lines.join("\n")}\n`;
}

export function parseArgs(args) {
  const parsed = { base: "origin/main", title: undefined, summary: false, help: false };

  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === "--title" || arg === "--base") {
      const value = args[index + 1];
      if (!value) {
        throw new Error(`${arg} requires a value`);
      }
      parsed[arg === "--title" ? "title" : "base"] = value;
      index += 1;
      continue;
    }
    if (arg === "--summary") {
      parsed.summary = true;
      continue;
    }
    if (arg === "--help" || arg === "-h") {
      parsed.help = true;
      continue;
    }
    throw new Error(`unknown argument: ${arg}`);
  }

  return parsed;
}

export async function main(args = forwardedArgs(), options = {}) {
  const parsed = parseArgs(args);
  if (parsed.help) {
    printUsage();
    return 0;
  }

  const root = options.repoRoot ?? repoRoot;
  let title = parsed.title;
  if (!title) {
    const head = await runCapture("git", ["log", "-1", "--format=%s"], { cwd: root });
    title = head.stdout.trim();
    console.log(`no --title given, checking the current HEAD subject: ${title}`);
  }

  const config =
    options.config ??
    parseSemanticConfig(await readFile(join(root, ".github/semantic.yml"), "utf8"));
  const files =
    options.files ?? (await gitChangedEntries(root, parsed.base)).map((entry) => entry.file);

  const report = checkPrTitle({ title, files, config });

  if (parsed.summary) {
    await writeSummary(
      renderStepSummary(report),
      options.summaryPath ?? process.env.GITHUB_STEP_SUMMARY,
    );
  }

  for (const warning of report.warnings) {
    console.warn(`pr title warning: ${warning.message}`);
  }

  if (report.ok) {
    console.log(`pr title: ok - ${report.nextAction}`);
    return 0;
  }

  console.error("pr title: failed");
  for (const error of report.errors) {
    console.error(`- ${error.message}`);
  }
  console.error(report.nextAction);
  return 1;
}

async function writeSummary(summary, summaryPath) {
  if (summaryPath) {
    await appendFile(summaryPath, summary);
    return;
  }
  console.log(summary);
}

function printUsage() {
  console.log(`Usage: node scripts/check-pr-title.mjs [--title <title>] [--base <ref>] [--summary]

Checks a PR title against .github/semantic.yml and against what the diff ships.
A "feat" or "fix" title fails when no changed file reaches a user of the SDKs,
CLI, API, console, or login UI. Omit --title to check the current HEAD subject.
Rule and worked examples: CONTRIBUTING.md#title-format.
`);
}

if (isDirectRun(import.meta.url)) {
  main().then(
    (code) => {
      process.exitCode = code;
    },
    (error) => {
      console.error(error instanceof Error ? error.message : String(error));
      process.exitCode = 1;
    },
  );
}
