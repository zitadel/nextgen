/**
 * Bundles apps/api/api/openapi into the documents the server embeds and the
 * docs site imports. Redocly's library and the repo's redocly.yaml, the same
 * way `redocly bundle` does.
 *
 * Targets:
 * - api: apps/api/api/openapi/bundled/openapi.json (full contract; go:embed)
 * - docs: apps/docs/.generated/openapi.mjs (+ types) and the error catalog
 */
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { basename, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { bundle, formatProblems, getTotals, loadConfig, parseYaml } from "@redocly/openapi-core";

import { isDirectRun } from "./dev-process.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const SPEC_ROOT = resolve(ROOT, "apps/api/api/openapi");
const SPEC = resolve(SPEC_ROOT, "openapi-spec.yaml");
const API_OUT = resolve(SPEC_ROOT, "bundled/openapi.json");
const DOCS_OUT = resolve(ROOT, "apps/docs/.generated");

// OpenAPI extension (not $comment): the served document must stay a valid
// OpenAPI object for strict validators and client generators.
const GENERATED_EXTENSION = "x-zitadel-generated";
const GENERATED_COMMENT = "generated by scripts/bundle-openapi.mjs. DO NOT EDIT";

/**
 * @param {{ api?: boolean, docs?: boolean, log?: (msg: string) => void }} [opts]
 */
export async function bundleOpenAPI({ api = false, docs = false, log = console.log } = {}) {
  if (!api && !docs) {
    throw new Error("bundleOpenAPI: pass api and/or docs");
  }

  const config = await loadConfig({ configPath: resolve(ROOT, "redocly.yaml") });
  const { bundle: result, problems } = await bundle({ ref: SPEC, config });
  const totals = getTotals(problems);
  if (totals.errors > 0) {
    formatProblems(problems, { format: "codeframe", totals });
    throw new Error(`bundling ${SPEC} failed with ${totals.errors} error(s)`);
  }

  if (api) {
    await writeApiBundle(result.parsed);
    log(`wrote ${API_OUT}`);
  }

  if (docs) {
    await writeDocsBundle(structuredClone(result.parsed));
    await writeErrorCatalog();
    log(`wrote ${DOCS_OUT}/openapi.mjs and errors.mjs`);
  }
}

/** Full contract for the server embed — no docs-only edits. */
async function writeApiBundle(document) {
  const stamped = { [GENERATED_EXTENSION]: GENERATED_COMMENT, ...document };
  await mkdir(resolve(SPEC_ROOT, "bundled"), { recursive: true });
  await writeFile(API_OUT, `${JSON.stringify(stamped, null, 2)}\n`);
}

/**
 * Docs import the bundle as a module. Optional project_id examples are stripped
 * so Fumadocs live forms do not default to the fictional example project.
 */
async function writeDocsBundle(document) {
  for (const parameter of Object.values(document.components?.parameters ?? {})) {
    if (parameter.in === "query" && parameter.name === "project_id" && !parameter.required) {
      delete parameter.example;
      delete parameter.examples;
    }
  }

  await mkdir(DOCS_OUT, { recursive: true });
  await writeFile(resolve(DOCS_OUT, "openapi.mjs"), `export default ${JSON.stringify(document, null, 2)};\n`);
  await writeFile(
    resolve(DOCS_OUT, "openapi.d.mts"),
    [
      'import type { OpenAPIV3_1 } from "fumadocs-openapi";',
      "",
      "declare const document: OpenAPIV3_1.Document;",
      "export default document;",
      "",
    ].join("\n"),
  );
}

async function writeErrorCatalog() {
  const schemasDir = join(SPEC_ROOT, "components/schemas/errors");
  const codeBySchema = new Map();
  for (const name of (await readdir(schemasDir)).filter((file) => file.endsWith(".yaml")).sort()) {
    const schema = parseYaml(await readFile(join(schemasDir, name), "utf8"));
    const code = schema.allOf?.find((part) => part.properties?.code)?.properties.code.const;
    const description = String(schema.description ?? "")
      .replace(/\s*Error code:[^\n]*\s*$/, "")
      .replace(/\s+/g, " ")
      .trim();
    if (typeof code !== "string" || description === "") {
      throw new Error(`${join(schemasDir, name)} names no error code or no description`);
    }
    codeBySchema.set(name, { code, description });
  }

  const errorSetSuffix = "-error-response.yaml";
  const errorSets = {};
  const endpoints = (await readdir(join(SPEC_ROOT, "endpoints"), { recursive: true }))
    .filter((file) => file.endsWith(errorSetSuffix))
    .sort();
  for (const file of endpoints) {
    const response = parseYaml(await readFile(join(SPEC_ROOT, "endpoints", file), "utf8"));
    const refs = response.content?.["application/json"]?.schema?.oneOf ?? [];
    errorSets[basename(file, errorSetSuffix)] = refs.map(({ $ref }) => {
      const known = codeBySchema.get(basename(String($ref)));
      if (!known) throw new Error(`${file} references ${$ref}, which is no error schema`);
      return known.code;
    });
  }

  await mkdir(DOCS_OUT, { recursive: true });
  await writeFile(
    resolve(DOCS_OUT, "errors.mjs"),
    `export default ${JSON.stringify({ codes: [...codeBySchema.values()], errorSets }, null, 2)};\n`,
  );
  await writeFile(
    resolve(DOCS_OUT, "errors.d.mts"),
    [
      'import type { ErrorCatalog } from "../lib/error-reference.ts";',
      "",
      "declare const catalog: ErrorCatalog;",
      "export default catalog;",
      "",
    ].join("\n"),
  );
}

if (isDirectRun(import.meta.url)) {
  const api = process.argv.includes("--api");
  const docs = process.argv.includes("--docs");
  try {
    await bundleOpenAPI({ api, docs });
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
