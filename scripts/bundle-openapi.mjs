/**
 * Bundles apps/api/api/openapi into the JSON the server embeds
 * (apps/api/api/openapi/bundled/openapi.json). Redocly's library and the
 * repo's redocly.yaml, the same way `redocly bundle` does.
 *
 * Docs consume that committed JSON via apps/docs/scripts/bundle-openapi.mjs
 * (MIT); this root script is server generate only.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { bundle, formatProblems, getTotals, loadConfig } from "@redocly/openapi-core";

import { isDirectRun } from "./dev-process.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const SPEC_ROOT = resolve(ROOT, "apps/api/api/openapi");
const SPEC = resolve(SPEC_ROOT, "openapi-spec.yaml");
const API_OUT = resolve(SPEC_ROOT, "bundled/openapi.json");

// OpenAPI extension (not $comment): the served document must stay a valid
// OpenAPI object for strict validators and client generators.
const GENERATED_EXTENSION = "x-zitadel-generated";
const GENERATED_COMMENT = "generated by scripts/bundle-openapi.mjs. DO NOT EDIT";

/**
 * @param {{ log?: (msg: string) => void }} [opts]
 */
export async function bundleOpenAPI({ log = console.log } = {}) {
  const config = await loadConfig({ configPath: resolve(ROOT, "redocly.yaml") });
  const { bundle: result, problems } = await bundle({ ref: SPEC, config });
  const totals = getTotals(problems);
  if (totals.errors > 0) {
    formatProblems(problems, { format: "codeframe", totals });
    throw new Error(`bundling ${SPEC} failed with ${totals.errors} error(s)`);
  }

  const stamped = { [GENERATED_EXTENSION]: GENERATED_COMMENT, ...result.parsed };
  await mkdir(resolve(SPEC_ROOT, "bundled"), { recursive: true });
  await writeFile(API_OUT, `${JSON.stringify(stamped, null, 2)}\n`);
  log(`wrote ${API_OUT}`);
}

if (isDirectRun(import.meta.url)) {
  if (!process.argv.includes("--api")) {
    console.error("usage: node scripts/bundle-openapi.mjs --api");
    process.exitCode = 1;
  } else {
    try {
      await bundleOpenAPI();
    } catch (error) {
      console.error(error.message);
      process.exitCode = 1;
    }
  }
}
