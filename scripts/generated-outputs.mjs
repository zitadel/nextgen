/**
 * The Go code-generation outputs, as one list.
 *
 * These globs mirror the `outputs` of the `server:generate` Moon task — keep
 * the two in sync. They are deliberately file-precise rather than
 * directory-wide: `internal/domain` holds hand-written code alongside its
 * generated `*_enumer.go`, so a directory-level pattern here would be a
 * destructive mistake waiting to happen.
 */
import { closeSync, globSync, openSync, readSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = fileURLToPath(new URL("..", import.meta.url));

export const GENERATED_GLOBS = [
  "api/generated/**/*.go",
  "api/openapi/components/schemas/errors/**/*.yaml",
  "api/openapi/endpoints/**/*-error-response.yaml",
  "internal/**/*_enumer.go",
  "internal/**/*.mock.go",
];

/**
 * Every generator here stamps a marker in the first few lines — ogen and
 * MockGen write "Code generated by …", gen_openapi_errors writes
 * "generated by …". Checking it is the safety net that makes deletion safe:
 * a glob that ever matches a hand-written file is caught here instead of
 * silently eating someone's work.
 */
const MARKER = /^(\/\/|#).*generated by .*DO NOT EDIT/im;

// Enough for the header every generator stamps in its first line or two.
const HEADER_BYTES = 512;

export function hasGeneratedMarker(absPath) {
  // Read from a descriptor rather than whole-file: the marker is always in the
  // header, and api/generated alone is megabytes of ogen output to slurp for a
  // line that cannot be below the first few. A multi-byte rune split at the
  // boundary decodes to a replacement char, which the marker never contains.
  const fd = openSync(absPath, "r");
  try {
    const header = Buffer.alloc(HEADER_BYTES);
    const read = readSync(fd, header, 0, HEADER_BYTES, 0);
    return MARKER.test(header.toString("utf8", 0, read));
  } finally {
    closeSync(fd);
  }
}

/**
 * Splits everything the globs match into files carrying the marker and files
 * that do not. Callers decide what to do with the strays; nothing here
 * deletes anything.
 */
export function collectGeneratedFiles() {
  const matched = GENERATED_GLOBS.flatMap((pattern) => globSync(pattern, { cwd: ROOT }));
  const unique = [...new Set(matched)].sort();

  const generated = [];
  const unmarked = [];
  for (const rel of unique) {
    (hasGeneratedMarker(join(ROOT, rel)) ? generated : unmarked).push(rel);
  }
  return { generated, unmarked };
}
