// gen_error_schemas generates individual OpenAPI error schema files.
// It automatically discovers all domain errors by parsing the domain package.
//
// Paths are calculated relative to this generator's location:
//   - Domain: ../../../internal/domain
//   - Output: ../../openapi/components/schemas/errors
package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"runtime"
	"strings"
)

func main() {
	// Get the directory where this generator is located
	_, filename, _, ok := runtime.Caller(0)
	if !ok {
		fmt.Fprintln(os.Stderr, "Failed to get current file path")
		os.Exit(1)
	}
	generatorDir := filepath.Dir(filename)

	// Calculate paths relative to generator location
	// Generator is at: api/cmd/gen_error_schemas/main.go
	domainPath := filepath.Join(generatorDir, "../../../internal/domain")
	outDir := filepath.Join(generatorDir, "../../openapi/components/schemas/errors")

	// Parse domain package to extract all errors
	errors := extractDomainErrors(domainPath)

	if err := os.MkdirAll(outDir, 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "mkdir error: %v\n", err)
		os.Exit(1)
	}

	for _, e := range errors {
		filename := strings.ReplaceAll(e.code, ".", "-") + ".yaml"
		path := filepath.Join(outDir, filename)

		content := fmt.Sprintf(`# Code generated by gen_error_schemas; DO NOT EDIT.
description: |
  %s
  
  Error code: %s
allOf:
  - $ref: ../../error-details.yaml
  - type: object
    properties:
      code:
        type: string
        const: %s
    required:
      - code
`, e.description, e.code, e.code)

		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			fmt.Fprintf(os.Stderr, "write %s: %v\n", filename, err)
			continue
		}
	}

	fmt.Printf("✅ Generated %d error schemas in %s\n", len(errors), outDir)
}

type errorInfo struct {
	code        string
	description string
}

func extractDomainErrors(domainPath string) []errorInfo {
	var errors []errorInfo

	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, domainPath, func(fi os.FileInfo) bool {
		return !strings.HasSuffix(fi.Name(), "_test.go") && fi.Name() != "cmd"
	}, parser.ParseComments)

	if err != nil {
		fmt.Fprintf(os.Stderr, "Error parsing domain: %v\n", err)
		os.Exit(1)
	}

	// First pass: collect all ResourcePrefix constants
	prefixes := extractResourcePrefixes(pkgs)

	for _, pkg := range pkgs {
		for _, file := range pkg.Files {
			ast.Inspect(file, func(n ast.Node) bool {
				funcDecl, ok := n.(*ast.FuncDecl)
				if !ok || !strings.HasPrefix(funcDecl.Name.Name, "Err") {
					return true
				}

				if funcDecl.Body == nil {
					return true
				}

				// Find newError() call
				for _, stmt := range funcDecl.Body.List {
					retStmt, ok := stmt.(*ast.ReturnStmt)
					if !ok {
						continue
					}

					for _, result := range retStmt.Results {
						if callExpr, ok := result.(*ast.CallExpr); ok {
							if ident, ok := callExpr.Fun.(*ast.Ident); ok && ident.Name == "newError" {
								if len(callExpr.Args) >= 2 {
									// Extract code (first arg) - can be string literal OR method call
									code := extractCodeArgument(callExpr.Args[0], prefixes)
									if code == "" {
										continue
									}

									// Extract message (second arg)
									msgLit, ok := callExpr.Args[1].(*ast.BasicLit)
									if !ok {
										continue
									}
									description := capitalizeFirst(strings.Trim(msgLit.Value, `"`))

									errors = append(errors, errorInfo{
										code:        code,
										description: description,
									})
								}
							}
						}
					}
				}

				return true
			})
		}
	}

	return errors
}

// extractResourcePrefixes finds all ResourcePrefix constants in the domain package
func extractResourcePrefixes(pkgs map[string]*ast.Package) map[string]string {
	prefixes := make(map[string]string)

	for _, pkg := range pkgs {
		for _, file := range pkg.Files {
			ast.Inspect(file, func(n ast.Node) bool {
				// Resource prefixes are normally const, but TokenPrefix is a
				// var — accept both, or its error codes go missing entirely.
				genDecl, ok := n.(*ast.GenDecl)
				if !ok || (genDecl.Tok != token.CONST && genDecl.Tok != token.VAR) {
					return true
				}

				for _, spec := range genDecl.Specs {
					valueSpec, ok := spec.(*ast.ValueSpec)
					if !ok {
						continue
					}

					// Check if type is ResourcePrefix
					if ident, ok := valueSpec.Type.(*ast.Ident); ok && ident.Name == "ResourcePrefix" {
						for i, name := range valueSpec.Names {
							if i < len(valueSpec.Values) {
								if lit, ok := valueSpec.Values[i].(*ast.BasicLit); ok {
									value := strings.Trim(lit.Value, `"`)
									prefixes[name.Name] = value
								}
							}
						}
					}
				}

				return true
			})
		}
	}

	return prefixes
}

// extractCodeArgument extracts the error code from either:
// 1. A string literal: "internal"
// 2. A method call: PrefixAuthAttempt.ErrorCodePrefix("not_found") -> "att.not_found"
func extractCodeArgument(arg ast.Expr, prefixes map[string]string) string {
	// Case 1: String literal
	if lit, ok := arg.(*ast.BasicLit); ok {
		return strings.Trim(lit.Value, `"`)
	}

	// Case 2: Method call like PrefixAuthAttempt.ErrorCodePrefix("not_found")
	if callExpr, ok := arg.(*ast.CallExpr); ok {
		// Check if it's a selector expression (something.method)
		if selExpr, ok := callExpr.Fun.(*ast.SelectorExpr); ok {
			// Check if method name is ErrorCodePrefix
			if selExpr.Sel.Name == "ErrorCodePrefix" {
				// Get the prefix identifier (e.g., PrefixAuthAttempt)
				if ident, ok := selExpr.X.(*ast.Ident); ok {
					prefixValue, ok := prefixes[ident.Name]
					if !ok {
						return ""
					}

					// Get the suffix from the method argument
					if len(callExpr.Args) > 0 {
						if suffixLit, ok := callExpr.Args[0].(*ast.BasicLit); ok {
							suffix := strings.Trim(suffixLit.Value, `"`)
							return prefixValue + "." + suffix
						}
					}
				}
			}
		}
	}

	return ""
}

func capitalizeFirst(s string) string {
	if len(s) == 0 {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}
