func TestCatalogEventTypesMatchDomain(t *testing.T) {
	t.Parallel()
	_, filename, _, ok := runtime.Caller(0)
	require.True(t, ok)
	generatorDir := filepath.Dir(filename)
	domainEventPath := filepath.Join(generatorDir, "../../../internal/domain/event.go")
	catalogPath := filepath.Join(generatorDir, "../../../../../docs/design/api/events-catalog.md")

	domainTypes, err := extractEventTypes(domainEventPath)
	require.NoError(t, err)
	domainSet := make(map[string]struct{}, len(domainTypes))
	for _, et := range domainTypes {
		domainSet[et] = struct{}{}
	}

	catalogRaw, err := os.ReadFile(catalogPath)
	require.NoError(t, err)
	// Path A, Path B, and Retired tables must match domain constants;
	// Deferred may list future types that are not yet constants.
	active := string(catalogRaw)
	if i := strings.Index(active, "## Deferred"); i >= 0 {
		active = active[:i]
	}
	// Match backtick-quoted event types in catalog tables, e.g. `user.created`.
	re := regexp.MustCompile("`([a-z][a-z0-9_.]+)`")
	catalogSet := map[string]struct{}{}
	for _, m := range re.FindAllStringSubmatch(active, -1) {
		et := m[1]
		if _, ok := payloadByEventType[et]; ok {
			catalogSet[et] = struct{}{}
		}
	}
	require.NotEmpty(t, catalogSet)

	for et := range catalogSet {
		_, ok := domainSet[et]
		assert.Truef(t, ok, "catalog event_type %q missing from domain.EventType constants", et)
	}
	for et := range domainSet {
		_, ok := catalogSet[et]
		assert.Truef(t, ok, "domain EventType %q missing from events-catalog.md", et)
	}
}

