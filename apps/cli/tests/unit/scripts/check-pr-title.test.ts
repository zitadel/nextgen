import { describe, expect, it } from "vitest";

type CheckPrTitleModule = {
  parseSemanticConfig: (source: string) => { types: string[]; scopes: string[] };
  parseConventionalTitle: (title: string) => {
    ok: boolean;
    type?: string;
    scope?: string;
    breaking?: boolean;
    summary?: string;
  };
  isNonShippingFile: (file: string) => boolean;
  suggestType: (files: string[]) => string;
  checkPrTitle: (options: {
    title: string;
    files: string[];
    config?: { types: string[]; scopes: string[] };
  }) => {
    ok: boolean;
    shipping: string[];
    errors: Array<{ code: string; message: string }>;
    warnings: Array<{ code: string; message: string }>;
    nextAction: string;
  };
  renderStepSummary: (report: unknown) => string;
  parseArgs: (args: string[]) => { base: string; title?: string; summary: boolean; help: boolean };
};

const load = async (): Promise<CheckPrTitleModule> =>
  (await import("../../../../../scripts/check-pr-title.mjs")) as unknown as CheckPrTitleModule;

const config = {
  types: ["feat", "fix", "docs", "refactor", "perf", "test", "build", "ci", "chore", "revert"],
  scopes: ["api", "config", "console", "database", "login", "deps", "security"],
};

describe("parseSemanticConfig", () => {
  it("reads the flat type and scope lists and drops comments", () => {
    const source = [
      "# Always validate the PR title",
      "titleOnly: true",
      "",
      "types:",
      "  - feat # new capability",
      "  - fix # corrects shipped behavior",
      "",
      "scopes:",
      "  # Backend",
      "  - api",
      "  - console",
    ].join("\n");

    expect(parseSemanticConfigOf(source)).resolves.toEqual({
      types: ["feat", "fix"],
      scopes: ["api", "console"],
    });
  });

  const parseSemanticConfigOf = async (source: string) =>
    (await load()).parseSemanticConfig(source);
});

describe("parseConventionalTitle", () => {
  it.each([
    ["feat: delete user", { type: "feat", scope: undefined, summary: "delete user" }],
    ["fix(login): keep the prompt", { type: "fix", scope: "login", summary: "keep the prompt" }],
    [
      "feat!: drop the v1 endpoint",
      { type: "feat", scope: undefined, summary: "drop the v1 endpoint" },
    ],
  ])("parses %s", async (title, expected) => {
    const { parseConventionalTitle } = await load();
    expect(parseConventionalTitle(title)).toMatchObject({ ok: true, ...expected });
  });

  it.each(["no type here", "feat:", "feat :missing space", ""])("rejects %s", async (title) => {
    const { parseConventionalTitle } = await load();
    expect(parseConventionalTitle(title).ok).toBe(false);
  });
});

