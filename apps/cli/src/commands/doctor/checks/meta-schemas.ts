import { META_SCHEMA_DIR } from "@zitadel/config/meta-schemas";

import {
  linkOnPath,
  metaSchemaState,
  projectMetaSchemas,
  type ProjectMetaSchema,
  writeMetaSchemas,
} from "@/lib/meta-schemas";
import type { CheckContext, CheckOutcome, SanityCheck } from "./types";

/**
 * The meta-schemas a project lacks and the ones that differ from this CLI's,
 * which `--fix` writes; the symlinks that keep others from being written; and
 * the files that cannot be read, with the reason.
 */
type MetaSchemaDrift = {
  missing: ProjectMetaSchema[];
  outdated: ProjectMetaSchema[];
  links: string[];
  unreadable: { path: string; reason: string }[];
};

/**
 * Verifies the editor meta-schemas in `.zitadel/meta/` match this CLI. Only
 * `setup` writes them, so a project set up by an older CLI lacks the dialects
 * added since and holds the ones that changed in their old version: a file's
 * `$schema` points at nothing, or editors and agents read outdated rules.
 *
 * They are CLI-owned generated output (ADR 042's amendment), never read by
 * `deploy` or the server, so a stale file only misleads the editor: that is
 * a warning, not a failure, and `--fix` rewrites them. A file there the CLI
 * does not ship is left alone. {@link metaSchemaState} decides what differs,
 * and when a symlink keeps a file from being written.
 *
 * A file that differs may as well come from a newer CLI. When the project
 * pins a `@zitadel/*` package to a newer version than this CLI, the train it
 * deploys with is newer, so this CLI reports the difference and writes
 * nothing: writing its own version back would make the editor disagree with
 * what `deploy` enforces.
 *
 * Implements {@link SanityCheck} directly: the abstract base can only pass or
 * fail.
 */
export class MetaSchemasCheck implements SanityCheck {
  readonly name = "meta-schemas";
  readonly path = META_SCHEMA_DIR;

  async run(ctx: CheckContext): Promise<CheckOutcome> {
    const base = { name: this.name, path: this.path };
    const { missing, outdated, links, unreadable } = await drift(ctx);
    if (
      missing.length === 0 &&
      outdated.length === 0 &&
      links.length === 0 &&
      unreadable.length === 0
    ) {
      return {
        ...base,
        status: "pass",
        message: "Editor schemas in .zitadel/meta/ match this CLI",
      };
    }
    const newer =
      missing.length > 0 || outdated.length > 0
        ? (await writeMetaSchemas(ctx.cwd, [...missing, ...outdated], { dryRun: true })).newerPin
        : undefined;
    const parts = [
      missing.length > 0 ? `${missing.length} missing` : undefined,
      outdated.length > 0 ? `${outdated.length} differ from this CLI's` : undefined,
      ...links.map((link) => `${link} is a symbolic link, not rewritten`),
      ...unreadable.map((file) => `${file.path} unreadable (${file.reason})`),
    ].filter((part) => part !== undefined);
    const next =
      newer !== undefined
        ? `; the project pins ${newer.name}@${newer.version}, newer than this CLI ` +
          `(${ctx.cliVersion}), so it leaves them to that version's doctor --fix.`
        : missing.length > 0 || outdated.length > 0
          ? "; doctor --fix writes this version's."
          : ".";
    return {
      ...base,
      status: "warn",
      message: `Editor schemas in .zitadel/meta/: ${parts.join(", ")}. They are generated by the CLI${next}`,
      details: {
        missing: missing.map((file) => file.path),
        outdated: outdated.map((file) => file.path),
        ...(links.length > 0 ? { linked: links } : {}),
        ...(unreadable.length > 0 ? { unreadable } : {}),
        ...(newer !== undefined ? { newer_pin: newer } : {}),
      },
    };
  }

  /**
   * Writes this CLI's version of every missing or outdated meta-schema through
   * {@link writeMetaSchemas}, which leaves a linked or unreadable file alone.
   * Writes nothing in a dry run, or when {@link writeMetaSchemas} refuses
   * because the project pins a newer `@zitadel/*` package than this CLI.
   *
   * @param ctx - The project and how to treat it.
   * @returns Nothing; what differs is read again by the next {@link run}.
   * @throws When a directory cannot be created or a file cannot be written.
   */
  async fix(ctx: CheckContext): Promise<void> {
    const { missing, outdated } = await drift(ctx);
    await writeMetaSchemas(ctx.cwd, [...missing, ...outdated], { dryRun: ctx.dryRun });
  }
}

/**
 * Sorts this CLI's meta-schemas by what the project holds of each. A symlink
 * that keeps files from being written is listed once, however many files lie
 * behind it.
 */
async function drift(ctx: CheckContext): Promise<MetaSchemaDrift> {
  const result: MetaSchemaDrift = { missing: [], outdated: [], links: [], unreadable: [] };
  for (const file of projectMetaSchemas(ctx.cliVersion)) {
    try {
      const state = await metaSchemaState(ctx.cwd, file);
      if (state === "linked") {
        const link = (await linkOnPath(ctx.cwd, file.path)) ?? file.path;
        if (!result.links.includes(link)) {
          result.links.push(link);
        }
      } else if (state !== "current") {
        result[state].push(file);
      }
    } catch (error) {
      result.unreadable.push({
        path: file.path,
        reason: error instanceof Error && "code" in error ? String(error.code) : String(error),
      });
    }
  }
  return result;
}
